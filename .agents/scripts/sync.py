#!/usr/bin/env python3
"""
Generate platform adapters from the canonical .agents/ tree.

Adapters are pointers, never content. .agents/ is the only place a rule or a
skill body lives, so there is nothing to keep in sync by hand and nothing that
can drift into two conflicting versions.

    python3 .agents/scripts/sync.py           # write adapters
    python3 .agents/scripts/sync.py --check   # fail if adapters differ from what we'd write
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
AGENTS = ROOT / ".agents"
MANIFEST = AGENTS / "manifest.json"
BANNER = "<!-- GENERATED by .agents/scripts/sync.py — DO NOT EDIT. Source: {src} -->"


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def title_from(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("title:"):
            return line.split(":", 1)[1].strip()
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem


def cursor_rule(rule: dict) -> tuple[Path, str]:
    src = f".agents/{rule['path']}"
    always = rule["scope"] == "always"
    globs = ", ".join(f'"{g}"' for g in rule["globs"])
    body = f"""---
description: {rule['description']}
globs: {globs}
alwaysApply: {'true' if always else 'false'}
---

{BANNER.format(src=src)}

# {title_from(AGENTS / rule['path'])}

Canonical source: `{src}`

Read that file and follow it. Statements marked **[H<n>] are hard** and binding.
Statements marked **[S<n>] are soft defaults** — deviate when the situation calls
for it, and state the reason in one line.

Conflicts resolve through `.agents/PRIORITY.md`.
"""
    return ROOT / ".cursor" / "rules" / f"{rule['id']}.mdc", body


def cursor_skill(skill: dict) -> tuple[Path, str]:
    src = f".agents/{skill['path']}"
    sk_id = skill["id"]
    body = f"""---
name: {sk_id}
description: {skill['when']} Full procedure lives at {src}.
---

{BANNER.format(src=src)}

# {sk_id}

This is a pointer. The skill body is at `{src}` — read it before acting.
Do not add content here; it will be overwritten by `.agents/scripts/sync.sh`.
"""
    return ROOT / ".cursor" / "skills" / sk_id / "SKILL.md", body


def generic_instructions_index(title: str, m: dict) -> str:
    always = [r for r in m["rules"] if r["scope"] == "always"]
    scoped = [r for r in m["rules"] if r["scope"] != "always"]

    lines = [
        BANNER.format(src=".agents/manifest.json"),
        "",
        f"# {title}",
        "",
        "Canonical content is in `.agents/`. This file is generated — edit `.agents/`,",
        "then run `.agents/scripts/sync.sh`.",
        "",
        "## Read first",
        "",
        "- `.agents/PRIORITY.md` — conflict resolution hierarchy",
        "- `.agents/CONVENTIONS.md` — what `[H<n>]` and `[S<n>]` mean",
        "- `.agents/config/defaults.md` — tunable technology defaults (all soft)",
        "",
        "**Hard rules `[H<n>]` are binding.** Violating one requires an explicit user",
        "override, stated aloud. **Soft defaults `[S<n>]` are starting points** — deviate",
        "with a one-line reason.",
        "",
        "## Always apply",
        "",
    ]
    for r in always:
        lines.append(f"- `.agents/{r['path']}` — {r['description']}")
    lines += ["", "## Apply when the files match", "", "| Rule | Applies to | Covers |", "|---|---|---|"]
    for r in scoped:
        g = ", ".join(f"`{x}`" for x in r["globs"][:4])
        if len(r["globs"]) > 4:
            g += f", +{len(r['globs']) - 4} more"
        lines.append(f"| `.agents/{r['path']}` | {g} | {r['description']} |")
    lines += ["", "## Skills — read the matching one before specialized work", "",
              "| Skill | When |", "|---|---|"]
    for s in m["skills"]:
        lines.append(f"| `.agents/{s['path']}` | {s['when']} |")
    lines += ["", "## Freshness", "",
              "Rules marked `freshness: tracked` cite law, vendor models, or external",
              "standards and go stale. Run `.agents/scripts/check-freshness.sh` before relying on",
              "them, and say so in your response when an entry is past due.", ""]
    return "\n".join(lines)


def claude_index(m: dict) -> tuple[Path, str]:
    return ROOT / ".claude" / "CLAUDE.md", generic_instructions_index("Project AI Rules (Claude Code)", m)


def copilot_index(m: dict) -> tuple[Path, str]:
    return ROOT / ".github" / "copilot-instructions.md", generic_instructions_index("Copilot Instructions (VS Code)", m)


def windsurf_index(m: dict) -> tuple[Path, str]:
    return ROOT / ".windsurfrules", generic_instructions_index("Windsurf Rules", m)


def cline_index(m: dict) -> tuple[Path, str]:
    return ROOT / ".clinerules", generic_instructions_index("Cline & Roo Code Rules", m)


def write(pairs: list[tuple[Path, str]], check: bool) -> int:
    failures = 0
    for path, body in pairs:
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != body:
                state = "missing" if current is None else "stale"
                print(f"DRIFT ({state}): {path.relative_to(ROOT)}")
                failures += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, encoding="utf-8")
    return failures


def main() -> int:
    check = "--check" in sys.argv
    m = load_manifest()

    pairs = [cursor_rule(r) for r in m["rules"]]
    pairs += [cursor_skill(s) for s in m["skills"]]
    pairs.append(claude_index(m))
    pairs.append(copilot_index(m))
    pairs.append(windsurf_index(m))
    pairs.append(cline_index(m))

    if not check:
        # Remove adapters for rules or skills that no longer exist.
        keep = {p for p, _ in pairs}
        for root in (ROOT / ".cursor", ROOT / ".claude"):
            if not root.exists():
                continue
            for f in root.rglob("*"):
                if f.is_file() and f not in keep:
                    print(f"removing orphan adapter: {f.relative_to(ROOT)}")
                    f.unlink()
            for d in sorted(root.rglob("*"), reverse=True):
                if d.is_dir() and not any(d.iterdir()):
                    d.rmdir()

        standalone = [
            ROOT / ".github" / "copilot-instructions.md",
            ROOT / ".windsurfrules",
            ROOT / ".clinerules",
        ]
        for f in standalone:
            if f.exists() and f not in keep:
                print(f"removing orphan adapter: {f.relative_to(ROOT)}")
                f.unlink()

    failures = write(pairs, check)

    if check:
        if failures:
            print(f"\n{failures} adapter(s) out of date. Run: .agents/scripts/sync.sh")
            return 1
        print(f"adapters up to date ({len(pairs)} files)")
        return 0

    print(f"generated {len(pairs)} adapter files from {len(m['rules'])} rules "
          f"and {len(m['skills'])} skills")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
